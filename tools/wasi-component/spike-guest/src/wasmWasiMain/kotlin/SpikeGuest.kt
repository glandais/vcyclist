private const val HTTP = "wasi:http/types@0.2.7"

@WasmImport(HTTP, "[constructor]fields")
private external fun fieldsNew(): Int

@WasmImport(HTTP, "[constructor]outgoing-request")
private external fun outgoingRequestNew(headers: Int): Int

/** `set-scheme(self, option<scheme>)` — `option` flattens to a discriminant, `scheme` to three. */
@WasmImport(HTTP, "[method]outgoing-request.set-scheme")
private external fun setScheme(
    self: Int,
    isSome: Int,
    schemeDisc: Int,
    ptr: Int,
    len: Int,
): Int

@WasmImport(HTTP, "[method]outgoing-request.set-authority")
private external fun setAuthority(
    self: Int,
    isSome: Int,
    ptr: Int,
    len: Int,
): Int

@WasmImport(HTTP, "[method]outgoing-request.set-path-with-query")
private external fun setPathWithQuery(
    self: Int,
    isSome: Int,
    ptr: Int,
    len: Int,
): Int

@WasmImport("wasi:http/outgoing-handler@0.2.7", "handle")
private external fun handleRequest(
    request: Int,
    optionsSome: Int,
    options: Int,
    retArea: Int,
)

@WasmImport(HTTP, "[method]future-incoming-response.subscribe")
private external fun futureSubscribe(self: Int): Int

@WasmImport("wasi:io/poll@0.2.7", "poll")
private external fun pollList(
    ptr: Int,
    len: Int,
    retArea: Int,
)

@WasmImport(HTTP, "[method]future-incoming-response.get")
private external fun futureGet(
    self: Int,
    retArea: Int,
)

@WasmImport(HTTP, "[method]incoming-response.status")
private external fun responseStatus(self: Int): Int

private fun writeUtf8(s: String): Pair<Int, Int> {
    val bytes = s.encodeToByteArray()
    val ptr = componentModelRealloc(0, 0, bytes.size)
    for (i in bytes.indices) (Pointer(ptr.toUInt()) + i).storeByte(bytes[i])
    return ptr to bytes.size
}

/**
 * GET `https://<authority><path>` and return its HTTP status, or a negative code.
 *
 * Everything below — the flattened `option<scheme>`, the return areas whose field offsets are
 * computed by hand, the poll loop — is what `wit-bindgen` generates in one command for Rust, C,
 * Go, JS and Python, and what nothing generates for Kotlin.
 */
@WasmExport("http-get-status")
fun httpGetStatus(
    authorityPtr: Int,
    authorityLen: Int,
    pathPtr: Int,
    pathLen: Int,
): Int {
    // Copy the arguments off the caller's realloc memory before anything else can touch it.
    val authority = ByteArray(authorityLen).also { b -> for (i in 0 until authorityLen) b[i] = (Pointer(authorityPtr.toUInt()) + i).loadByte() }.decodeToString()
    val path = ByteArray(pathLen).also { b -> for (i in 0 until pathLen) b[i] = (Pointer(pathPtr.toUInt()) + i).loadByte() }.decodeToString()
    return try {
        val request = outgoingRequestNew(fieldsNew())
        // scheme: option::some(scheme::HTTPS) — HTTPS is case 1, no payload.
        check(setScheme(request, 1, 1, 0, 0) == 0) { "set-scheme refused" }
        val (aPtr, aLen) = writeUtf8(authority)
        check(setAuthority(request, 1, aPtr, aLen) == 0) { "set-authority refused" }
        val (pPtr, pLen) = writeUtf8(path)
        check(setPathWithQuery(request, 1, pPtr, pLen) == 0) { "set-path-with-query refused" }

        // Layouts below are 8-aligned with *byte* discriminants, measured with `http-debug`,
        // not read off the spec: `result<own<future-incoming-response>, error-code>` puts its
        // handle at +8, and `option<result<result<own<incoming-response>, error-code>, ()>>`
        // puts its at +24.
        val ret = componentModelRealloc(0, 0, 64)
        handleRequest(request, 0, 0, ret)
        if (Pointer(ret.toUInt()).loadByte().toInt() != 0) return -2
        val future = (Pointer(ret.toUInt()) + 8).loadInt()

        val pollable = futureSubscribe(future)
        val listPtr = componentModelRealloc(0, 0, 4)
        Pointer(listPtr.toUInt()).storeInt(pollable)
        val pollRet = componentModelRealloc(0, 0, 8)

        var rounds = 0
        while (rounds++ < 100) {
            val get = componentModelRealloc(0, 0, 64)
            futureGet(future, get)
            if (Pointer(get.toUInt()).loadByte().toInt() != 0) {
                if ((Pointer(get.toUInt()) + 8).loadByte().toInt() != 0) return -3 // future already taken
                if ((Pointer(get.toUInt()) + 16).loadByte().toInt() != 0) return -4 // err(error-code)
                return responseStatus((Pointer(get.toUInt()) + 24).loadInt())
            }
            pollList(listPtr, 1, pollRet)
        }
        -5 // never resolved
    } catch (e: Throwable) {
        lastError = e.toString()
        -1
    }
}

/** Same sequence, stopping after `step`, to find which hand-computed layout is wrong. */
@WasmExport("http-debug")
fun httpDebug(
    authorityPtr: Int,
    authorityLen: Int,
    pathPtr: Int,
    pathLen: Int,
    step: Int,
): Int {
    val authority = ByteArray(authorityLen).also { b -> for (i in 0 until authorityLen) b[i] = (Pointer(authorityPtr.toUInt()) + i).loadByte() }.decodeToString()
    val path = ByteArray(pathLen).also { b -> for (i in 0 until pathLen) b[i] = (Pointer(pathPtr.toUInt()) + i).loadByte() }.decodeToString()
    return try {
        val fields = fieldsNew()
        if (step == 1) return fields
        val request = outgoingRequestNew(fields)
        if (step == 2) return request
        val scheme = setScheme(request, 1, 1, 0, 0)
        if (step == 3) return scheme
        val (aPtr, aLen) = writeUtf8(authority)
        val auth = setAuthority(request, 1, aPtr, aLen)
        if (step == 4) return auth
        val (pPtr, pLen) = writeUtf8(path)
        val pq = setPathWithQuery(request, 1, pPtr, pLen)
        if (step == 5) return pq
        val ret = componentModelRealloc(0, 0, 32)
        for (i in 0 until 8) (Pointer(ret.toUInt()) + i * 4).storeInt(-77)
        handleRequest(request, 0, 0, ret)
        if (step in 6..13) return (Pointer(ret.toUInt()) + (step - 6) * 4).loadInt()
        // `result<own<future-incoming-response>, error-code>` is 8-aligned: a *byte* discriminant
        // at 0, the handle at 8. Measured, not deduced — step 6..13 above is how.
        if ((Pointer(ret.toUInt()).loadByte().toInt()) != 0) return -2
        val future = (Pointer(ret.toUInt()) + 8).loadInt()
        if (step == 14) return future
        val pollable = futureSubscribe(future)
        if (step == 15) return pollable
        val listPtr = componentModelRealloc(0, 0, 4)
        Pointer(listPtr.toUInt()).storeInt(pollable)
        val pollRet = componentModelRealloc(0, 0, 8)
        pollList(listPtr, 1, pollRet)
        if (step == 16) return Pointer(pollRet.toUInt()).loadInt()
        val get = componentModelRealloc(0, 0, 64)
        for (i in 0 until 16) (Pointer(get.toUInt()) + i * 4).storeInt(-77)
        futureGet(future, get)
        if (step in 17..32) return (Pointer(get.toUInt()) + (step - 17) * 4).loadInt()
        -99
    } catch (e: Throwable) {
        lastError = e.toString()
        -1
    }
}
