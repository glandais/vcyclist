/**
 * `wasi:random/random.get-random-bytes: func(len: u64) -> list<u8>`, called by hand.
 *
 * This is the cheapest possible component-model *import*: no argument to lower, one `list<u8>`
 * to lift. The core import is what the Canonical ABI lowers that to — the guest allocates the
 * return area and passes its pointer, the callee writes `(ptr, len)` into it.
 *
 * `wasi:http` is this, fourteen times over, with resource handles, a pollable and nested
 * `result` variants whose payload offsets have to be computed by hand. Nothing generates it.
 */
@WasmImport("wasi:random/random@0.2.7", "get-random-bytes")
private external fun getRandomBytes(
    len: Long,
    retArea: Int,
)

@WasmExport("random-sum")
fun randomSum(n: Int): Int =
    try {
        val retArea = componentModelRealloc(0, 0, 8)
        getRandomBytes(n.toLong(), retArea)
        val ptr = Pointer(retArea.toUInt()).loadInt()
        val len = (Pointer(retArea.toUInt()) + 4).loadInt()
        var sum = 0
        for (i in 0 until len) sum += (Pointer(ptr.toUInt()) + i).loadByte().toInt() and 0xFF
        // len is returned too, so the caller can tell "0 bytes" from "not called".
        len * 100000 + sum
    } catch (e: Throwable) {
        lastError = e.toString()
        -1
    }

