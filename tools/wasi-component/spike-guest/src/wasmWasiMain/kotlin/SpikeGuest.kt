/*
 * Throwaway guest for the w13 spike. **Not production, not built by the vcyclist Gradle build**
 * — its world is `../../spike.wit`, its verdict `docs/archive/plans/wasm-wasi-component-model.md`.
 *
 * Exports named as the Canonical ABI wants them, over the real engine. The one that matters is
 * `parse-gpx: func(gpx: string) -> s32`: it takes the string **directly out of linear memory**,
 * where the host put it through `cabi_realloc`, instead of asking for it back through
 * `vcyclist.read_input` — that is ABI v1 §4 replaced by the Canonical ABI.
 *
 * The rest are probes, and each one measured something the verdict quotes:
 *
 * | Export | What it established |
 * |---|---|
 * | `str-len` | an inbound `string` crosses intact (23 694 characters of `stelvio.gpx`) |
 * | `probe-scoped` | **the wall**: no scoped allocation is possible while the caller's memory lives |
 * | `parse-gpx-freeing` | the workaround, and that it is repeatable |
 * | `last-error` | an outbound `string`, hand-written return area included |
 * | `random-sum` | a component-model *import* is callable from Kotlin |
 * | `http-get-status` | `wasi:http` really fetches — HTTP 200 from the DEM server |
 * | `http-debug` | how the return-area offsets were found: by probing, not by reading a spec |
 *
 * Nothing here is idiomatic and nothing here should be copied into production. Every line of it
 * is what `wit-bindgen` writes for other languages.
 */
private val paths = HashMap<Int, Path>()
private var next = 1

/**
 * The allocator the Canonical ABI requires of any component that receives a `string` or a `list`.
 * `componentModelRealloc` is `@ComponentModelInternalApi` — "should not be used outside of code
 * generated by the compiler and toolchain" — so this line is exactly the decision n°2 of
 * `PLAN-WASM-WASI.md` being reopened, and the verdict has to say so.
 */
@WasmExport("cabi_realloc")
fun cabiRealloc(
    oldPtr: Int,
    oldSize: Int,
    align: Int,
    newSize: Int,
): Int {
    // Kotlin 2.4.20-Beta2's signature is `componentModelRealloc(originalPtr, originalSize,
    // newSize)`: **no alignment parameter**. The Canonical ABI passes one, and this wrapper has
    // to drop it on the floor. It happens to work here (the allocator aligns to 8, which covers
    // string, list<u8> and list<f64>) but nothing in the stdlib promises it — one more reason the
    // verdict calls this API internal rather than adoptable.
    check(align in 1..8) { "unsupported alignment $align" }
    return componentModelRealloc(oldPtr, oldSize, newSize)
}

@WasmExport("abi-version")
fun abiVersion(): Int = 1

@WasmExport("parse-gpx")
fun parseGpx(
    ptr: Int,
    len: Int,
): Int {
    val bytes = ByteArray(len)
    val base = Pointer(ptr.toUInt())
    for (i in 0 until len) bytes[i] = (base + i).loadByte()
    val path = GpxParser.parse(bytes.decodeToString()).firstTrackAsPath()
    val handle = next++
    paths[handle] = path
    return handle
}

@WasmExport("total-distance")
fun totalDistance(handle: Int): Double = paths[handle]?.totalDistance ?: -1.0

@WasmExport("path-size")
fun pathSize(handle: Int): Int = paths[handle]?.size ?: -1

/** Debug: does the Canonical ABI string transfer itself work, before any engine code runs? */
@WasmExport("str-len")
fun strLen(
    ptr: Int,
    len: Int,
): Int {
    val bytes = ByteArray(len)
    val base = Pointer(ptr.toUInt())
    for (i in 0 until len) bytes[i] = (base + i).loadByte()
    return bytes.decodeToString().length
}

/** Debug: the parse, with the failure turned into a returned code instead of an exception. */
@WasmExport("try-parse")
fun tryParse(
    ptr: Int,
    len: Int,
): Int {
    val bytes = ByteArray(len)
    val base = Pointer(ptr.toUInt())
    for (i in 0 until len) bytes[i] = (base + i).loadByte()
    return try {
        val path = GpxParser.parse(bytes.decodeToString()).firstTrackAsPath()
        val handle = next++
        paths[handle] = path
        handle
    } catch (e: Throwable) {
        lastError = e.toString()
        -1
    }
}

private var lastError = ""

@WasmExport("last-error-len")
fun lastErrorLen(): Int = lastError.encodeToByteArray().size

/**
 * An **outbound** `string`, the Canonical ABI way: a function whose result needs more than one
 * core value returns a **pointer to a return area** the guest allocated itself, into which it
 * writes `(ptr, len)`; the bytes live in memory allocated with `cabi_realloc` and the caller
 * releases both through `cabi_post_return`.
 *
 * The first attempt used the older "caller passes the return area" shape, `(param i32) -> ()`,
 * and `wasm-tools component new` refused it with `expected [] -> [I32] but found [I32] -> []` —
 * the kind of detail that is generated code's business, not a human's.
 *
 * `write_output` and its copy-during-the-call rule disappear; the ~15 lines below are what
 * replaces them, and in a real component they would be compiler-generated rather than hand-written.
 */
@WasmExport("last-error")
fun lastErrorOut(): Int {
    val bytes = lastError.encodeToByteArray()
    val ptr = componentModelRealloc(0, 0, bytes.size)
    for (i in bytes.indices) (Pointer(ptr.toUInt()) + i).storeByte(bytes[i])
    val retArea = componentModelRealloc(0, 0, 8)
    Pointer(retArea.toUInt()).storeInt(ptr)
    (Pointer(retArea.toUInt()) + 4).storeInt(bytes.size)
    return retArea
}

/** Probe: is *any* scoped allocation forbidden while the host's string is still alive? */
@WasmExport("probe-scoped")
fun probeScoped(
    ptr: Int,
    len: Int,
): Int =
    try {
        kotlin.wasm.unsafe.withScopedMemoryAllocator { it.allocate(8); 1 }
    } catch (e: Throwable) {
        lastError = e.toString()
        -1
    }

/**
 * The workaround: copy the argument onto the GC heap, hand the linear memory back, *then* work.
 * If this returns a handle, the incompatibility is a discipline rather than a wall — at the price
 * of freeing memory the caller believes it still owns until `cabi_post_return`.
 */
@WasmExport("parse-gpx-freeing")
fun parseGpxFreeing(
    ptr: Int,
    len: Int,
): Int {
    val bytes = ByteArray(len)
    val base = Pointer(ptr.toUInt())
    for (i in 0 until len) bytes[i] = (base + i).loadByte()
    return try {
        kotlin.wasm.unsafe.freeAllComponentModelReallocAllocatedMemory()
        val path = GpxParser.parse(bytes.decodeToString()).firstTrackAsPath()
        val handle = next++
        paths[handle] = path
        handle
    } catch (e: Throwable) {
        lastError = e.toString()
        -1
    }
}

